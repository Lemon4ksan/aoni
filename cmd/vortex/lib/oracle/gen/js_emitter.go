// GenerateJS compiles an OracleSpec AST into a standalone, universal Node.js sidecar script using aoni/ast/js.
func GenerateJS(s *spec.OracleSpec) ([]byte, error) {
	if s == nil {
		return nil, errors.New("oracle spec is nil")
	}

	port := s.Port
	if port <= 0 {
		port = 64055
	}

	poolSize := s.Browser.PoolSize
	if poolSize <= 0 {
		poolSize = 3
	}

	prog := js.NewProgram(
		js.StmtRaw("// Code generated by Vortex Universal Oracle Compiler. DO NOT EDIT."),
		js.StmtRaw("// Oracle Name: "+s.Name),
		js.StmtRaw("// Target URL:  "+s.TargetURL),
		// Dependencies
		js.Require("http", "path", "fs", "os"),
		js.RequireFrom("playwright", "chromium"),
		// Constants & Configuration
		js.Const("PORT", js.Raw("process.env.ORACLE_PORT || "+strconv.Itoa(port))),
		js.Const("TARGET_URL", js.Raw("process.env.ORACLE_TARGET_URL || "+fmt.Sprintf("%q", s.TargetURL))),
		js.Const("HEADLESS", js.Raw("process.env.HEADLESS !== 'false' && "+strconv.FormatBool(s.Browser.Headless))),
		js.Const("PROXY_URL", js.Raw("process.env.ORACLE_PROXY || "+fmt.Sprintf("%q", s.Browser.Proxy))),
		js.Const(
			"POOL_SIZE",
			js.Raw("process.env.ORACLE_POOL_SIZE ? parseInt(process.env.ORACLE_POOL_SIZE) : "+strconv.Itoa(poolSize)),
		),
		// State & Page Pool
		js.Let("browserContext", nil),
		js.Const("pagePool", js.Raw("[]")),
		js.Const("waitingQueue", js.Raw("[]")),
		js.Const("capturedTokensMap", js.Raw("new Map()")),
		// Browser Discovery
		js.StmtRaw(buildBrowserDiscoveryJS()),
		// JSONPath & Extraction Helper
		js.StmtRaw(buildJSONPathHelperJS()),
		// Cookie Helper
		js.StmtRaw(buildCookieHelperJS()),
		// Kinetics Helpers
		js.StmtRaw(buildKineticsHelpersJS()),
		// Dialog Dismissal
		buildDismissDialogsFn(s),
		// Interceptors Setup
		buildSetupPageInterceptorsFn(s),
		// Page Pool Management
		buildPagePoolManagerJS(s),
		// Browser Lifecycle Initialization
		buildInitBrowserFn(s),
		// Flow Execution Engine
		buildExecuteFlowFn(s),
		// HTTP & SSE Streaming Server
		buildHTTPServerStmt(s),
	)

	code, err := js.Format(prog)
	if err != nil {
		return nil, fmt.Errorf("formatting generated JS AST: %w", err)
	}

	return []byte(code), nil
}

func buildBrowserDiscoveryJS() string {
	return `function findSystemBrowser() {
  const customPath = process.env.BROWSER_PATH || process.env.CHROME_PATH;
  if (customPath && fs.existsSync(customPath)) {
    return { path: customPath, source: 'environment variable' };
  }

  const commonPaths = [
    // Windows standard paths
    path.join(os.homedir(), 'AppData', 'Local', 'imput', 'Helium', 'Application', 'chrome.exe'),
    'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
    'C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe',
    path.join(os.homedir(), 'AppData', 'Local', 'Google', 'Chrome', 'Application', 'chrome.exe'),
    'C:\\Program Files\\BraveSoftware\\Brave-Browser\\Application\\brave.exe',
    'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
    'C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe',

    // macOS standard paths
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Helium.app/Contents/MacOS/Helium',
    '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',
    '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
    '/Applications/Chromium.app/Contents/MacOS/Chromium',

    // Linux standard paths
    '/usr/bin/google-chrome',
    '/usr/bin/google-chrome-stable',
    '/usr/bin/chromium',
    '/usr/bin/chromium-browser',
    '/usr/bin/brave-browser',
    '/snap/bin/chromium',
  ];

  for (const p of commonPaths) {
    if (p && fs.existsSync(p)) {
      const name = p.includes('Helium') ? 'Helium' : path.basename(p);
      return { path: p, source: ` + "`auto-detected (${name})`" + ` };
    }
  }

  return { path: undefined, source: 'default bundled Chromium' };
}`
}

func buildJSONPathHelperJS() string {
	return `function extractByJSONPath(obj, jsonPath) {
  if (!obj || !jsonPath) return obj;
  const parts = jsonPath.split('.');
  let curr = obj;
  for (const p of parts) {
    if (curr == null) return null;
    const arrayMatch = p.match(/^(\w+)\[(\d+)\]$/);
    if (arrayMatch) {
      curr = curr[arrayMatch[1]];
      if (Array.isArray(curr)) curr = curr[parseInt(arrayMatch[2])];
    } else {
      curr = curr[p];
    }
  }
  return curr;
}`
}

func buildCookieHelperJS() string {
	return `function parseCookieHeader(headerStr) {
  if (!headerStr) return [];
  const parts = headerStr.split(';');
  const cookies = [];
  for (const part of parts) {
    const trimmed = part.trim();
    if (!trimmed) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const name = trimmed.substring(0, eqIdx).trim();
      const value = trimmed.substring(eqIdx + 1).trim();
      cookies.push({
        name,
        value,
        domain: new URL(TARGET_URL).hostname,
        path: '/',
      });
    }
  }
  return cookies;
}`
}

func buildKineticsHelpersJS() string {
	return `async function humanType(page, text) {
  for (const char of text) {
    await page.keyboard.type(char, { delay: 10 + Math.random() * 25 });
  }
}

async function humanClick(page, locator) {
  const box = await locator.boundingBox();
  if (box) {
    const x = box.x + box.width / 2 + (Math.random() * 6 - 3);
    const y = box.y + box.height / 2 + (Math.random() * 6 - 3);
    await page.mouse.move(x, y, { steps: 5 });
  }
  await locator.click();
}`
}

func buildDismissDialogsFn(s *spec.OracleSpec) js.Stmt {
	if len(s.Browser.DismissSelectors) == 0 {
		return js.Fn("dismissDialogs").Async().Args("page").Body(
			js.StmtRaw("// No custom dismissal selectors specified"),
		)
	}

	selectorsJSON, _ := json.Marshal(s.Browser.DismissSelectors)

	return js.StmtRaw(fmt.Sprintf(`async function dismissDialogs(page) {
  const selectors = %s;
  for (const sel of selectors) {
    try {
      const btn = page.locator(sel).first();
      if (await btn.isVisible({ timeout: 800 })) {
        await btn.click();
        console.log('[oracle] dismissed dialog: ' + sel);
        await page.waitForTimeout(200);
      }
    } catch (e) {}
  }
}`, string(selectorsJSON)))
}

func buildSetupPageInterceptorsFn(s *spec.OracleSpec) js.Stmt {
	var (
		reqRules  strings.Builder
		respRules strings.Builder
	)

	for _, flow := range s.Flows {
		pattern := flow.Intercept.URLPattern
		if pattern == "" {
			continue
		}

		switch flow.Intercept.Source {
		case "", spec.SourceRequestBody:
			fmt.Fprintf(&reqRules, `    if (url.includes(%q) && req.method() === 'POST') {
      try {
        const postData = req.postData();
        if (postData) {
          const parsed = JSON.parse(postData);
          let token = null;
          if (%d > 0 && Array.isArray(parsed) && parsed.length > %d) {
            token = parsed[%d];
          } else if (%q) {
            token = extractByJSONPath(parsed, %q);
          }
          if (token && (typeof token === 'string' || typeof token === 'object')) {
            const list = capturedTokensMap.get(page) || [];
            list.push({ token, headers: req.headers(), url, source: 'request_body' });
            if (list.length > 10) list.shift();
            capturedTokensMap.set(page, list);
          }
        }
      } catch (e) {}
    }
`, pattern, flow.Intercept.TokenIndex, flow.Intercept.TokenIndex, flow.Intercept.TokenIndex,
				flow.Intercept.JSONPath, flow.Intercept.JSONPath)

		case spec.SourceResponseBody:
			fmt.Fprintf(&respRules, `    if (url.includes(%q)) {
      try {
        const bodyText = await resp.text();
        const parsed = JSON.parse(bodyText);
        let token = null;
        if (%q) {
          token = extractByJSONPath(parsed, %q);
        } else {
          token = parsed;
        }
        if (token) {
          const list = capturedTokensMap.get(page) || [];
          list.push({ token, headers: resp.headers(), url, source: 'response_body' });
          if (list.length > 10) list.shift();
          capturedTokensMap.set(page, list);
        }
      } catch (e) {}
    }
`, pattern, flow.Intercept.JSONPath, flow.Intercept.JSONPath)
		}
	}

	return js.StmtRaw(fmt.Sprintf(`async function setupPageInterceptors(page) {
  page.on('request', async req => {
    const url = req.url();
%s  });

  page.on('response', async resp => {
    const url = resp.url();
%s  });
}`, reqRules.String(), respRules.String()))
}

func buildPagePoolManagerJS(_ *spec.OracleSpec) js.Stmt {
	return js.StmtRaw(`async function setupPage(page) {
  capturedTokensMap.set(page, []);
  await setupPageInterceptors(page);
}

async function acquirePage() {
  await initBrowser();

  // 1. Check if an idle warm page exists in pool
  if (pagePool.length > 0) {
    const page = pagePool.pop();
    capturedTokensMap.set(page, []);
    return page;
  }

  // 2. If pool limit not reached, spawn a new page in context
  const currentPages = browserContext.pages();
  if (currentPages.length < POOL_SIZE) {
    const page = await browserContext.newPage();
    await setupPage(page);
    try {
      await page.goto(TARGET_URL, { waitUntil: 'domcontentloaded', timeout: 35000 });
      await page.waitForTimeout(1000);
      await dismissDialogs(page);
    } catch (e) {}
    capturedTokensMap.set(page, []);
    return page;
  }

  // 3. Queue request until a page is released
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      const idx = waitingQueue.findIndex(item => item.resolve === resolve);
      if (idx !== -1) waitingQueue.splice(idx, 1);
      reject(new Error('timeout waiting for available browser page in pool'));
    }, 45000);

    waitingQueue.push({ resolve, timer });
  });
}

function releasePage(page) {
  capturedTokensMap.set(page, []);
  if (waitingQueue.length > 0) {
    const next = waitingQueue.shift();
    clearTimeout(next.timer);
    next.resolve(page);
  } else {
    pagePool.push(page);
  }
}`)
}

func buildInitBrowserFn(s *spec.OracleSpec) js.Stmt {
	return js.StmtRaw(fmt.Sprintf(`let initPromise = null;

async function initBrowser(rawCookies = null) {
  if (browserContext) {
    if (rawCookies) {
      const cookies = parseCookieHeader(rawCookies);
      await browserContext.addCookies(cookies);
    }
    return;
  }

  if (initPromise) return initPromise;

  initPromise = (async () => {
    try {
      const detected = findSystemBrowser();
      console.log('[oracle] using browser at: ' + (detected.path || 'bundled') + ' [' + detected.source + ']');
      
      const proxyServer = PROXY_URL || process.env.HTTP_PROXY || process.env.HTTPS_PROXY;
      const proxyOpt = proxyServer ? { server: proxyServer } : undefined;
      if (proxyOpt) console.log('[oracle] proxy routing enabled: ' + proxyServer);

      const tmpDir = path.join(os.tmpdir(), 'aoni_oracle_%s');
      browserContext = await chromium.launchPersistentContext(tmpDir, {
        headless: HEADLESS,
        executablePath: detected.path,
        proxy: proxyOpt,
        viewport: { width: 1280, height: 800 },
        args: [
          '--disable-blink-features=AutomationControlled',
          '--disable-infobars',
          '--no-sandbox',
          '--disable-setuid-sandbox'
        ]
      });

      if (rawCookies) {
        const cookies = parseCookieHeader(rawCookies);
        await browserContext.addCookies(cookies);
      }

      const initialPages = browserContext.pages();
      const firstPage = initialPages.length > 0 ? initialPages[0] : await browserContext.newPage();
      await setupPage(firstPage);
      await firstPage.goto(TARGET_URL, { waitUntil: 'domcontentloaded', timeout: 45000 });
      await firstPage.waitForTimeout(1000);
      await dismissDialogs(firstPage);
      pagePool.push(firstPage);

      console.log('[oracle] browser ready on ' + TARGET_URL + ' (pool size: ' + POOL_SIZE + ')');
    } finally {
      initPromise = null;
    }
  })();

  return initPromise;
}`, s.Name))
}

func buildExecuteFlowFn(s *spec.OracleSpec) js.Stmt {
	var flowBranches strings.Builder

	for _, flow := range s.Flows {
		fmt.Fprintf(&flowBranches, `  if (!flowName || flowName === %q) {
    try {
`, flow.Name)

		// Check if Flow has explicit Steps defined
		if len(flow.Steps) > 0 {
			for _, step := range flow.Steps {
				switch step.Action {
				case spec.ActionClick:
					fmt.Fprintf(&flowBranches, `      const elem = page.locator(%q).first();
      await elem.waitFor({ state: 'visible', timeout: %d });
      if (%t) { await humanClick(page, elem); } else { await elem.click(); }
      await page.waitForTimeout(100);
`, step.Selector, defaultTimeout(step.Timeout, 8000), step.Kinetics)

				case spec.ActionType:
					fmt.Fprintf(&flowBranches, `      const input = page.locator(%q).first();
      await input.waitFor({ state: 'visible', timeout: %d });
      await input.click();
      const textToType = (%q).replace('{content}', content || '');
      if (%t) { await humanType(page, textToType); } else { await input.fill(textToType); }
      await page.waitForTimeout(100);
`, step.Selector, defaultTimeout(step.Timeout, 8000), step.Value, step.Kinetics)

				case spec.ActionSelect:
					fmt.Fprintf(&flowBranches, `      await page.locator(%q).first().selectOption(%q);
      await page.waitForTimeout(100);
`, step.Selector, step.Value)

				case spec.ActionWaitVisible:
					fmt.Fprintf(
						&flowBranches,
						`      await page.locator(%q).first().waitFor({ state: 'visible', timeout: %d });
`,
						step.Selector,
						defaultTimeout(step.Timeout, 10000),
					)

				case spec.ActionWaitHidden:
					fmt.Fprintf(
						&flowBranches,
						`      await page.locator(%q).first().waitFor({ state: 'hidden', timeout: %d });
`,
						step.Selector,
						defaultTimeout(step.Timeout, 10000),
					)

				case spec.ActionHotkey:
					fmt.Fprintf(&flowBranches, `      await page.keyboard.press(%q);
      await page.waitForTimeout(100);
`, step.Value)

				case spec.ActionEval:
					fmt.Fprintf(&flowBranches, `      await page.evaluate(%q);
`, step.Value)

				case spec.ActionDelay:
					fmt.Fprintf(&flowBranches, `      await page.waitForTimeout(%s);
`, step.Value)
				}
			}
		} else {
			// Legacy Input/Submit execution for backward compatibility
			fmt.Fprintf(&flowBranches, `      const input = page.locator(%q).first();
      if (await input.isVisible({ timeout: 3000 })) {
        await humanClick(page, input);
        await page.keyboard.press('Control+A');
        await page.keyboard.press('Backspace');
        await page.waitForTimeout(60);

        await humanType(page, content || 'hello');
        await page.waitForTimeout(150);

        const submit = page.locator(%q).first();
        if (await submit.isVisible({ timeout: 1000 })) {
          await humanClick(page, submit);
        } else {
          await page.keyboard.press(%q);
        }
      }
`, flow.InputSelector, flow.SubmitSelector, flow.FallbackShortcut)
		}

		// Multi-Source Extraction Logic for this Flow
		switch flow.Intercept.Source {
		case spec.SourceLocalStorage:
			fmt.Fprintf(&flowBranches, `      const tokenVal = await page.evaluate(k => localStorage.getItem(k), %q);
      if (tokenVal) return { token: tokenVal, headers: {}, source: 'local_storage' };
`, flow.Intercept.Key)

		case spec.SourceSessionStorage:
			fmt.Fprintf(&flowBranches, `      const tokenVal = await page.evaluate(k => sessionStorage.getItem(k), %q);
      if (tokenVal) return { token: tokenVal, headers: {}, source: 'session_storage' };
`, flow.Intercept.Key)

		case spec.SourceGlobalJS:
			fmt.Fprintf(
				&flowBranches,
				`      const tokenVal = await page.evaluate(expr => { try { return eval(expr); } catch(e) { return null; } }, %q);
      if (tokenVal) return { token: tokenVal, headers: {}, source: 'global_js' };
`,
				flow.Intercept.Key,
			)

		case spec.SourceDOMAttr:
			fmt.Fprintf(&flowBranches, `      const tokenVal = await page.locator(%q).first().getAttribute(%q);
      if (tokenVal) return { token: tokenVal, headers: {}, source: 'dom_attr' };
`, flow.Intercept.Selector, flow.Intercept.Attr)

		default:
			// Network request/response capture loop
			fmt.Fprintf(&flowBranches, `      for (let i = 0; i < 50; i++) {
        await page.waitForTimeout(150);
        const list = capturedTokensMap.get(page) || [];
        if (list.length > 0) {
          return list.pop();
        }
      }
`)
		}

		fmt.Fprintf(&flowBranches, `    } catch (e) {
      console.warn('[oracle] flow %q warning:', e.message);
    }
    const list = capturedTokensMap.get(page) || [];
    if (list.length > 0) return list.pop();
  }
`, flow.Name)
	}

	return js.StmtRaw(fmt.Sprintf(`async function executeFlowOnPage(page, flowName, content) {
  await dismissDialogs(page);

%s
  throw new Error('failed to capture token for flow: ' + flowName);
}`, flowBranches.String()))
}

func buildHTTPServerStmt(s *spec.OracleSpec) js.Stmt {
	return js.StmtRaw(fmt.Sprintf(`const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `+"`http://${req.headers.host}`"+`);

  if (req.method === 'POST' && url.pathname === '/init') {
    let body = '';
    req.on('data', chunk => { body += chunk; });
    req.on('end', async () => {
      try {
        const data = JSON.parse(body || '{}');
        await initBrowser(data.cookies);
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ status: 'ok', poolSize: POOL_SIZE }));
      } catch (err) {
        res.writeHead(500, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: err.message }));
      }
    });
    return;
  }

  if (req.method === 'POST' && url.pathname === '/token' || req.method === 'GET' && url.pathname === '/token') {
    let body = '';
    req.on('data', chunk => { body += chunk; });
    req.on('end', async () => {
      let page = null;
      try {
        let content = '';
        let flowName = '';
        if (body) {
          try {
            const data = JSON.parse(body);
            content = data.content || '';
            flowName = data.flow || '';
          } catch (e) {}
        }
        page = await acquirePage();
        const item = await executeFlowOnPage(page, flowName, content);
        const token = typeof item === 'object' ? item.token : item;
        const reqHeaders = typeof item === 'object' ? (item.headers || {}) : {};

        let cookieHeader = '';
        if (browserContext) {
          try {
            const cList = await browserContext.cookies();
            cookieHeader = cList.map(c => `+"`${c.name}=${c.value}`"+`).join('; ');
          } catch (e) {}
        }

        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({
          status: 'ok',
          token,
          headers: reqHeaders,
          cookies: cookieHeader,
          source: item ? item.source : 'unknown'
        }));
      } catch (err) {
        res.writeHead(500, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: err.message }));
      } finally {
        if (page) releasePage(page);
      }
    });
    return;
  }

  if (req.method === 'POST' && url.pathname === '/stream') {
    let body = '';
    req.on('data', chunk => { body += chunk; });
    req.on('end', async () => {
      let page = null;
      try {
        res.writeHead(200, {
          'Content-Type': 'text/event-stream',
          'Cache-Control': 'no-cache',
          'Connection': 'keep-alive'
        });

        page = await acquirePage();
        res.write(`+"`data: ${JSON.stringify({ event: 'acquired_tab' })}\\n\\n`"+`);
        
        let content = '';
        let flowName = '';
        if (body) {
          try {
            const data = JSON.parse(body);
            content = data.content || '';
            flowName = data.flow || '';
          } catch (e) {}
        }

        const item = await executeFlowOnPage(page, flowName, content);
        res.write(`+"`data: ${JSON.stringify({ event: 'token', data: item })}\\n\\n`"+`);
        res.write(`+"`data: ${JSON.stringify({ event: 'done' })}\\n\\n`"+`);
        res.end();
      } catch (err) {
        res.write(`+"`data: ${JSON.stringify({ event: 'error', error: err.message })}\\n\\n`"+`);
        res.end();
      } finally {
        if (page) releasePage(page);
      }
    });
    return;
  }

  if (req.method === 'GET' && url.pathname === '/status') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({
      status: 'ok',
      poolSize: POOL_SIZE,
      idleTabs: pagePool.length,
      waitingQueue: waitingQueue.length
    }));
    return;
  }

  res.writeHead(404, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify({ error: 'Not found' }));
});

server.listen(PORT, '127.0.0.1', () => {
  console.log(`+"`🤖 Vortex Universal Oracle [%q] listening on http://127.0.0.1:${PORT}`"+`);
  initBrowser().catch(err => {
    console.log('[oracle] background init notice:', err.message);
  });
});`, s.Name))
}

func defaultTimeout(timeout, fallback int) int {
	if timeout > 0 {
		return timeout
	}

	return fallback
}
